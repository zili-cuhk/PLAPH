function plaph_v2_run_task(experiment, task_index, out_root, varargin)
%PLAPH_V2_RUN_TASK Run one chunk of replications of the v2 campaign.
%
%   plaph_v2_run_task("main", 17, "/path/to/out")
%   plaph_v2_run_task("main", 17, "/path/to/out", "SplineOrder", 3)
%
% task_index enumerates (scenario row, chunk) pairs of plaph_v2_manifest
% in row-major order; plaph_v2_task_count(experiment) gives the total.
% A chunk whose results file already exists is skipped (safe resubmission).

parser = inputParser;
parser.addParameter("ChunkSize", 5, @(x) isscalar(x) && x >= 1);
parser.addParameter("SplineOrder", 3, @(x) any(x == [3 4]));  % pilot decision 2026-10-21: quadratic
parser.addParameter("TuningMode", "grid_ebic", @(x) any(strcmpi(string(x), ...
    ["fixed" "grid_ebic" "grid_bic"])));
parser.addParameter("FixedCL", 1.5, @(x) isscalar(x) && x > 0);
parser.addParameter("FixedKappa", 0.20, @(x) isscalar(x) && x > 0);
parser.addParameter("MaxOuterIter", 6000, @(x) isscalar(x) && x >= 1);
parser.addParameter("TuningGridCL", [0.5 1.0 1.5 2.0 2.5], @(x) isnumeric(x) && all(x > 0));
parser.addParameter("TuningGridKappa", [0.03 0.05 0.075 0.10 0.15], @(x) isnumeric(x) && all(x > 0));
parser.addParameter("ExportRoot", "", @(x) ischar(x) || isstring(x));
parser.parse(varargin{:});
o = parser.Results;

experiment = lower(string(experiment));
M = plaph_v2_manifest(experiment);
[row, chunk, rep_start, rep_end] = plaph_v2_task_map(M, task_index, o.ChunkSize);
r = M(row,:);
chunk_dir = fullfile(char(out_root), char(experiment), char(r.scenario_id), ...
    sprintf("chunk_%03d_reps_%03d_%03d", chunk, rep_start, rep_end));
if isfile(fullfile(chunk_dir, "PLAPH_simulation_results.mat"))
    fprintf("Chunk already complete: %s\n", chunk_dir);
    return;
end
if ~isfolder(chunk_dir)
    mkdir(chunk_dir);
end

tuning_mode = string(o.TuningMode);
if experiment == "xi_sensitivity"
    % Kink-coefficient sensitivity at fixed (c_L, kappa); set FixedCL and
    % FixedKappa to the modal EBIC choices of the main study before running.
    tuning_mode = "fixed";
end
screen_size = min(r.dimension, round(0.30*r.n));
export_dir = "";
methods = r.methods;
export_root = string(o.ExportRoot);
if experiment == "grpsurv_export" && strlength(export_root) == 0
    export_root = fullfile(string(out_root), "grpsurv_data");
end
if strlength(export_root) > 0
    export_dir = fullfile(export_root, r.scenario_id);
end
args = { ...
    "R", rep_end-rep_start+1, ...
    "BaseSeed", r.seed_root + 1000*r.seed_scenario + rep_start - 1, ...
    "DiscriminatingSampleSizes", r.n, ...
    "DiscriminatingDimensions", r.dimension, ...
    "DiscriminatingCensorRates", r.target_censor_rate, ...
    "DiscriminatingTauValues", r.tau, ...
    "DiscriminatingCensoringScale", r.censoring_scale, ...
    "DiscriminatingRho", r.rho, ...
    "DiscriminatingFailureScale", 1, ...
    "DiscriminatingAdditiveSignalScale", 2, ...
    "DiscriminatingCensoringFunctionDesign", "shared_balanced_bounded", ...
    "GenerateCopulaOverride", r.generate_copula, ...
    "FitCopulaOverride", r.fit_copula, ...
    "MethodsOverride", methods, ...
    "MICPenaltyScale", o.FixedCL, ...
    "MICPenaltyNormalization", "mean", ...
    "MICPenaltyScaleFailure", o.FixedCL, ...
    "MICPenaltyScaleCensoring", o.FixedCL, ...
    "LinearMICForm", "kinked", ...
    "LinearKinkCoefficient", r.xi, ...
    "ThresholdLinear", 5e-4, ...
    "InitialLinearStrategy", "legacy", ...
    "InitialLinearCap", Inf, ...
    "InitialSplineStrategy", "group_lasso", ...
    "InitialSplinePilotScale", 0.25, ...
    "InitialSplineWeighting", "none", ...
    "MPLDecomposablePilotIterations", 100, ...
    "MPLDecomposablePilotLinearScale", 1, ...
    "MPLDecomposablePilotGroupScale", 0.5, ...
    "MPLDecomposablePilotStart", "initial", ...
    "MPLDecomposablePilotWeighting", "adaptive", ...
    "MPLDecomposablePilotGroupWeightGamma", 1, ...
    "MPLStepScale", 0.25, ...
    "MPLStepStrategy", "fixed", ...
    "MPLOracleRefitFminconPolish", true, ...
    "MPLCollectModelBasedInference", true, ...
    "SplineGroupPenaltyType", "group_iht", ...
    "SplineGroupPenaltyNormalization", "mean", ...
    "SplineBasisScaling", "center", ...
    "SplineSelectionMetric", "effect", ...
    "ThresholdSpline", 0, ...
    "SplineGroupIHTThresholdFailure", o.FixedKappa, ...
    "SplineGroupIHTThresholdCensoring", o.FixedKappa, ...
    "SplineGroupIHTWarmupIterations", 0, ...
    "SplineGroupIHTContinuationIterations", 0, ...
    "SplineGroupIHTStartFraction", 1, ...
    "PreScreeningType", "dual_margin_rank_fused_information", ...
    "ScreenLinearSize", screen_size, ...
    "ScreenAdditiveSize", screen_size, ...
    "ScreenAdditiveRank", 9, ...
    "PostSelectionRefitType", "joint_oracle", ...
    "PostSelectionRefitMaxIter", 1000, ...
    "BaselineBinCount", 10, ...
    "NumInternalKnots", 4, ...
    "BaselineRoughnessScale", 0, ...
    "MaxOuterIter", o.MaxOuterIter, ...
    "CollectDiagnostics", true, ...
    "CollectFunctionFits", true, ...
    "FunctionFitGridSize", 101, ...
    "UseParallel", false, ...
    "SaveCheckpoints", true, ...
    "OutputDir", chunk_dir, ...
    "DryRun", false, ...
    "SplineOrder", o.SplineOrder, ...
    "TuningMode", tuning_mode, ...
    "TuningGridCL", o.TuningGridCL, ...
    "TuningGridKappa", o.TuningGridKappa, ...
    "PLVersion", "v2", ...
    "ExportDataDir", export_dir};
if isfinite(r.fit_tau)
    args = [args, {"FitTauOverride", r.fit_tau}];
end
t0 = tic;
run_PLAPH_simulation("informative_discrimination", args{:});
fprintf("Task %d (%s, scenario %d, reps %d-%d) finished in %.1f min.\n", ...
    task_index, experiment, r.scenario_index, rep_start, rep_end, toc(t0)/60);
end
